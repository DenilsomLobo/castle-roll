function setup(module) {
  const elements=new Map(),stored=new Map(),events=new Map();
  function element(){return {children:[],textContent:'',hidden:false,disabled:false,replaceChildren(){this.children=[];},appendChild(child){this.children.push(child);}};}
  const context={crypto:require('node:crypto'),window:{CastleRuntime:{ranking:'firestore'},CastleLevels:[{},{},{}],addEventListener:(name,fn)=>events.set(name,fn)},document:{querySelector(selector){if(!elements.has(selector))elements.set(selector,element());return elements.get(selector);},createElement:element},localStorage:{get length(){return stored.size;},key:index=>[...stored.keys()][index],getItem:key=>stored.get(key)||null,setItem:(key,value)=>stored.set(key,value),removeItem:key=>stored.delete(key)},setTimeout,clearTimeout,console:{warn(){}},loadFirebase:()=>Promise.resolve({authenticatePlayer:async()=>({uid:'test'}),...module})};
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(path.join(root,'player-name.js'),'utf8'),context);
  context.window.CastlePlayerName=context.CastlePlayerName;
  vm.runInContext(fs.readFileSync(path.join(root,'ranking-sync.js'),'utf8'),context);
  context.window.CastleRankingSync=context.CastleRankingSync;
  vm.runInContext(fs.readFileSync(path.join(root,'ranking-client.js'),'utf8').replace("import('./firebase-ranking.js')","loadFirebase()"),context);
  return {api:context.window.CastleRanking,elements,stored,events};
}
